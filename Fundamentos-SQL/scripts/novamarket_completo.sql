-- NovaMarket - modelo operacional canónico
CREATE TABLE clientes (
    id_cliente NUMBER PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    correo VARCHAR2(150),
    ciudad VARCHAR2(100) NOT NULL
);
CREATE TABLE productos (
    id_producto NUMBER PRIMARY KEY,
    nombre VARCHAR2(120) NOT NULL,
    categoria VARCHAR2(80) NOT NULL,
    precio NUMBER(10,2) NOT NULL CHECK (precio >= 0),
    stock NUMBER NOT NULL CHECK (stock >= 0)
);
CREATE TABLE ventas (
    id_venta NUMBER PRIMARY KEY,
    id_cliente NUMBER NOT NULL,
    fecha_venta DATE NOT NULL,
    CONSTRAINT fk_ventas_cliente FOREIGN KEY (id_cliente) REFERENCES clientes(id_cliente)
);
CREATE TABLE detalle_ventas (
    id_detalle NUMBER PRIMARY KEY,
    id_venta NUMBER NOT NULL,
    id_producto NUMBER NOT NULL,
    cantidad NUMBER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMBER(10,2) NOT NULL CHECK (precio_unitario >= 0),
    CONSTRAINT fk_detalle_venta FOREIGN KEY (id_venta) REFERENCES ventas(id_venta),
    CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto) REFERENCES productos(id_producto)
);

